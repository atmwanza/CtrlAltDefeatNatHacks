"""Build static/icons.js from the Tabler Icons SVGs in static/vendor/tabler-icons/.

Only the icons DrawDx uses are downloaded (Tabler Icons 3.51.0, MIT; see the LICENSE file there).
icons.js inlines them, so the page makes no extra requests and works offline:
  tiIcon('circle-check')        -> '<svg class="icon" ...>...</svg>'
  <span data-icon="eraser"></span> in HTML is filled in when icons.js runs.

Run:  python tools/build_icons.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'static' / 'vendor' / 'tabler-icons'
OUT = ROOT / 'static' / 'icons.js'

paths = {}
for svg in sorted(SRC.glob('*.svg')):
    body = re.search(r'<svg[^>]*>(.*)</svg>', svg.read_text(encoding='utf-8'), re.S).group(1)
    body = re.sub(r'<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*/>', '', body)   # Tabler's empty bounding box
    paths[svg.stem] = re.sub(r'\s+', ' ', body).replace('> <', '><').strip()

OUT.write_text(f"""// Tabler Icons 3.51.0 (MIT, static/vendor/tabler-icons/LICENSE), inlined so the page works offline.
// Generated by tools/build_icons.py; edit that, not this file.
(() => {{
  const PATHS = {json.dumps(paths, indent=2)};
  window.tiIcon = (name, cls = '') =>
    `<svg xmlns="http://www.w3.org/2000/svg" class="icon${{cls ? ' ' + cls : ''}}" width="24" height="24" viewBox="0 0 24 24"`
    + ` fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"`
    + ` aria-hidden="true" focusable="false">${{PATHS[name] || ''}}</svg>`;
  // <span data-icon="name"></span> -> inline SVG (scripts sit at the end of <body>, so the markup is there)
  window.fillIcons = (root = document) => root.querySelectorAll('[data-icon]').forEach(el => {{
    if (!el.firstElementChild) el.innerHTML = window.tiIcon(el.dataset.icon);
  }});
  window.fillIcons();
}})();
""", encoding='utf-8')
print(f'wrote {OUT.relative_to(ROOT)}: {len(paths)} icons')
